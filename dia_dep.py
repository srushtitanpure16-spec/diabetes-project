import pandas as pd
import streamlit as st

from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression

# Page title
st.title("Diabetes Prediction: Logistic Regression")
st.write("Enter the patient's details to predict the diabetes outcome.")

# Sidebar inputs
st.sidebar.header("Patient Input Parameters")

def user_input_features():
    pregnancies = st.sidebar.number_input(
        "Pregnancies", min_value=0, max_value=20, value=1
    )
    glucose = st.sidebar.number_input(
        "Glucose", min_value=0, max_value=300, value=120
    )
    blood_pressure = st.sidebar.number_input(
        "Blood Pressure", min_value=0, max_value=200, value=70
    )
    skin_thickness = st.sidebar.number_input(
        "Skin Thickness", min_value=0, max_value=100, value=20
    )
    insulin = st.sidebar.number_input(
        "Insulin", min_value=0, max_value=1000, value=80
    )
    bmi = st.sidebar.number_input(
        "BMI", min_value=0.0, max_value=80.0, value=30.0
    )
    diabetes_pedigree = st.sidebar.number_input(
        "Diabetes Pedigree Function",
        min_value=0.0, max_value=3.0, value=0.5
    )
    age = st.sidebar.number_input(
        "Age", min_value=1, max_value=120, value=30
    )

    data = {
        "Pregnancies": pregnancies,
        "Glucose": glucose,
        "BloodPressure": blood_pressure,
        "SkinThickness": skin_thickness,
        "Insulin": insulin,
        "BMI": bmi,
        "DiabetesPedigreeFunction": diabetes_pedigree,
        "Age": age
    }

    return pd.DataFrame([data])


# Get user input
df = user_input_features()

st.subheader("Patient Input Parameters")
st.write(df)

# Load dataset
try:
    diabetes = pd.read_csv("diabetes.csv")

    # Separate input features and target
    X = diabetes.drop("Outcome", axis=1)
    y = diabetes["Outcome"]

    # Use the same feature order as the dataset
    df = df[X.columns]

    # Treat impossible zero measurements as missing values
    # Pregnancies and Outcome are not changed
    zero_columns = [
        "Glucose", "BloodPressure", "SkinThickness", "Insulin", "BMI"
    ]

    X[zero_columns] = X[zero_columns].replace(0, float("nan"))

    # Logistic Regression model
    model = Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler()),
        ("classifier", LogisticRegression(max_iter=1000))
    ])

    # Train model
    model.fit(X, y)

    # Predict
    prediction = model.predict(df)
    prediction_proba = model.predict_proba(df)

    # Display result
    st.subheader("Predicted Result")

    if prediction[0] == 1:
        st.error("The model predicts: Diabetes")
    else:
        st.success("The model predicts: No Diabetes")

    # Display probabilities
    st.subheader("Prediction Probability")

    st.write(
        f"No Diabetes: {prediction_proba[0][0] * 100:.2f}%"
    )
    st.write(
        f"Diabetes: {prediction_proba[0][1] * 100:.2f}%"
    )

except FileNotFoundError:
    st.error(
        "diabetes.csv not found. Place the CSV file in the same "
        "folder as this Python program."
    )

except (KeyError, ValueError) as e:
    st.error(f"Please check the CSV column names and data: {e}")